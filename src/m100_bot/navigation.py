def help_page(section: str = "overview") -> tuple[str, InlineKeyboardMarkup]:
    from html import escape

    if section not in HELP_SECTIONS:
        text = HELP_OVERVIEW
        rows = [
            [InlineKeyboardButton(text=HELP_SECTIONS[key][0], callback_data=f"help:{key}")]
            for key in HELP_SECTIONS
        ]
    else:
        title, intro, examples, note = HELP_SECTIONS[section]
        text = f"<b>{title}</b>\n\n{intro}\n\n"
        text += "\n\n".join(
            f"<b>{escape(label)}</b>\n<blockquote>{escape(phrase)}</blockquote>"
            for label, phrase in examples
        )
        text += f"\n\n<i>{escape(note)}</i>"
        rows = [[InlineKeyboardButton(text="‹ Все разделы", callback_data="help:overview")]]
    rows.append([InlineKeyboardButton(text="⌂ Главное меню", callback_data="nav:restart")])
    return text, InlineKeyboardMarkup(inline_keyboard=rows)
