"""PostgreSQL persistence. SQL transactions never include external API requests."""

import hashlib
import secrets
import time

import psycopg
from psycopg.types.json import Jsonb

from .domain import Draft, Operation, UserError

DDL = """
CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY);
CREATE TABLE IF NOT EXISTS drafts (
    id TEXT PRIMARY KEY, user_id BIGINT NOT NULL, payload JSONB NOT NULL,
    seq BIGINT GENERATED ALWAYS AS IDENTITY UNIQUE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX IF NOT EXISTS drafts_owner ON drafts (user_id, seq DESC);
CREATE TABLE IF NOT EXISTS operations (
    id TEXT PRIMARY KEY, draft_id TEXT UNIQUE NOT NULL, payload JSONB NOT NULL,
    seq BIGINT GENERATED ALWAYS AS IDENTITY UNIQUE
);
CREATE INDEX IF NOT EXISTS operations_day ON operations ((payload->>'day'));
CREATE TABLE IF NOT EXISTS web_links (
    token_hash TEXT PRIMARY KEY, draft_id TEXT NOT NULL,
    user_id BIGINT NOT NULL, expires_at DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS web_links_expiry ON web_links (expires_at);
CREATE TABLE IF NOT EXISTS user_profiles (user_id BIGINT PRIMARY KEY, payload JSONB NOT NULL);
CREATE TABLE IF NOT EXISTS conversation_turns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL, chat_id BIGINT NOT NULL,
    role TEXT NOT NULL, content TEXT NOT NULL, created_at DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS conversation_owner ON conversation_turns (user_id, chat_id, id DESC);
CREATE TABLE IF NOT EXISTS table_selections (
    user_id BIGINT, chat_id BIGINT, spreadsheet_id TEXT, sheet_name TEXT,
    payload JSONB NOT NULL, PRIMARY KEY (user_id, chat_id, spreadsheet_id, sheet_name)
);
CREATE TABLE IF NOT EXISTS telegram_updates (
    update_id BIGINT PRIMARY KEY, payload JSONB NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    retry_at DOUBLE PRECISION NOT NULL DEFAULT 0,
    completed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS telegram_updates_pending ON telegram_updates (update_id)
    WHERE completed_at IS NULL;
INSERT INTO schema_migrations VALUES (1) ON CONFLICT DO NOTHING;
INSERT INTO schema_migrations VALUES (2) ON CONFLICT DO NOTHING;
"""


class Store:
    def __init__(self, database_url: str):
        if not database_url:
            raise UserError("Укажите DATABASE_URL для PostgreSQL.")
        try:
            self.db = psycopg.connect(database_url, autocommit=True, connect_timeout=10)
            with self.db.transaction():
                # Serialize initial schema creation, including concurrent first startup.
                self.db.execute("SELECT pg_advisory_xact_lock(100, 1)")
                self.db.execute(DDL)
        except psycopg.Error:
            if hasattr(self, "db"):
                self.db.close()
            raise UserError(
                "Не удалось подключиться к PostgreSQL. Проверьте DATABASE_URL."
            ) from None

    def try_acquire_writer(self, project: str) -> bool:
        key = int.from_bytes(hashlib.sha256(project.encode()).digest()[:8], signed=True)
        return self.db.execute("SELECT pg_try_advisory_lock(%s)", (key,)).fetchone()[0]

    def enqueue_update(self, update: dict) -> None:
        self.db.execute(
            "INSERT INTO telegram_updates(update_id,payload) VALUES (%s,%s) "
            "ON CONFLICT(update_id) DO NOTHING",
            (update["update_id"], Jsonb(update)),
        )

    def pending_update(self) -> tuple | None:
        return self.db.execute(
            "SELECT update_id,payload,attempts FROM telegram_updates "
            "WHERE completed_at IS NULL AND retry_at<=%s ORDER BY update_id LIMIT 1",
            (time.time(),),
        ).fetchone()

    def finish_update(self, update_id: int) -> None:
        # Retain only the ID for deduplication once personal message data is no longer needed.
        self.db.execute(
            "UPDATE telegram_updates SET completed_at=clock_timestamp(),payload='{}'::jsonb "
            "WHERE update_id=%s",
            (update_id,),
        )
        self.db.execute("DELETE FROM telegram_updates WHERE completed_at<now()-interval '7 days'")

    def retry_update(self, update_id: int, attempts: int) -> None:
        self.db.execute(
            "UPDATE telegram_updates SET attempts=attempts+1,retry_at=%s WHERE update_id=%s",
            (time.time() + min(300, 2 ** min(attempts + 1, 9)), update_id),
        )

    def acquire_writer(self, project: str) -> None:
        """One Telegram consumer/writer per source table, even across different machines."""
        if not self.try_acquire_writer(project):
            raise UserError("Для этой таблицы уже запущен бот. Остановите другой экземпляр.")

    def _save_draft(self, draft: Draft) -> None:
        self.db.execute(
            "INSERT INTO drafts(id,user_id,payload) VALUES (%s,%s,%s) "
            "ON CONFLICT(id) DO UPDATE SET user_id=EXCLUDED.user_id, "
            "payload=EXCLUDED.payload, updated_at=clock_timestamp()",
            (draft.id, draft.user_id, Jsonb(draft.model_dump(mode="json"))),
        )

    def save_draft(self, draft: Draft) -> None:
        self._save_draft(draft)

    def remember(self, user_id: int, chat_id: int, role: str, content: str) -> None:
        with self.db.transaction():
            self.db.execute(
                "INSERT INTO conversation_turns(user_id,chat_id,role,content,created_at) "
                "VALUES (%s,%s,%s,%s,%s)",
                (user_id, chat_id, role, content[:6000], time.time()),
            )
            self.db.execute(
                "DELETE FROM conversation_turns WHERE user_id=%s AND chat_id=%s AND id NOT IN "
                "(SELECT id FROM conversation_turns WHERE user_id=%s AND chat_id=%s "
                "ORDER BY id DESC LIMIT 40)",
                (user_id, chat_id, user_id, chat_id),
            )

    def history(self, user_id: int, chat_id: int) -> list[dict]:
        rows = self.db.execute(
            "SELECT role,content FROM conversation_turns WHERE user_id=%s AND chat_id=%s "
            "ORDER BY id DESC LIMIT 16",
            (user_id, chat_id),
        ).fetchall()
        return [{"role": role, "content": content[:1800]} for role, content in reversed(rows)]

    def selection(self, user_id: int, chat_id: int, spreadsheet_id: str, sheet_name: str):
        row = self.db.execute(
            "SELECT payload FROM table_selections WHERE user_id=%s AND chat_id=%s "
            "AND spreadsheet_id=%s AND sheet_name=%s",
            (user_id, chat_id, spreadsheet_id, sheet_name),
        ).fetchone()
        return row[0] if row else None

    def save_selection(self, user_id, chat_id, spreadsheet_id, sheet_name, selection) -> None:
        self.db.execute(
            "INSERT INTO table_selections VALUES (%s,%s,%s,%s,%s) "
            "ON CONFLICT(user_id,chat_id,spreadsheet_id,sheet_name) "
            "DO UPDATE SET payload=EXCLUDED.payload",
            (user_id, chat_id, spreadsheet_id, sheet_name, Jsonb(selection)),
        )

    def user_operations(self, user_id: int, chat_id: int, spreadsheet_id: str) -> list[Operation]:
        rows = self.db.execute(
            "SELECT o.payload,d.user_id,d.payload FROM operations o "
            "LEFT JOIN drafts d ON d.id=o.draft_id ORDER BY o.seq DESC",
        ).fetchall()
        result = []
        for payload, owner, draft_payload in rows:
            op = Operation.model_validate(payload)
            if (op.user_id if op.user_id is not None else owner) != user_id:
                continue
            source_chat = op.chat_id
            if source_chat is None and draft_payload:
                source_chat = draft_payload["chat_id"]
            if source_chat == chat_id and op.spreadsheet_id in {"", spreadsheet_id}:
                result.append(op)
        return result

    def profile(self, user_id: int) -> dict | None:
        row = self.db.execute(
            "SELECT payload FROM user_profiles WHERE user_id=%s", (user_id,)
        ).fetchone()
        return row[0] if row else None

    def save_profile(self, user_id: int, values: dict) -> dict:
        with self.db.transaction():
            row = self.db.execute(
                "INSERT INTO user_profiles VALUES (%s,%s) ON CONFLICT(user_id) DO UPDATE "
                "SET payload=user_profiles.payload || EXCLUDED.payload RETURNING payload",
                (user_id, Jsonb(values)),
            ).fetchone()
        return row[0]

    def draft_owner(self, draft_id: str) -> int | None:
        row = self.db.execute("SELECT user_id FROM drafts WHERE id=%s", (draft_id,)).fetchone()
        return row[0] if row else None

    def get_draft(self, draft_id: str, user_id: int) -> Draft:
        row = self.db.execute(
            "SELECT payload FROM drafts WHERE id=%s AND user_id=%s", (draft_id, user_id)
        ).fetchone()
        if not row:
            raise UserError("Черновик не найден. Отправьте новый отчёт.")
        return Draft.model_validate(row[0])

    def finish_save(self, draft: Draft, continuation: Draft | None) -> None:
        with self.db.transaction():
            self._save_draft(draft)
            if continuation:
                self._save_draft(continuation)

    def pending_drafts(self, user_id: int, *, offset: int = 0, limit: int = 6) -> list[Draft]:
        rows = self.db.execute(
            "SELECT payload FROM drafts WHERE user_id=%s AND payload->>'status' "
            "IN ('draft','saving') ORDER BY updated_at DESC,seq DESC LIMIT %s OFFSET %s",
            (user_id, limit, max(0, offset)),
        ).fetchall()
        return [Draft.model_validate(row[0]) for row in rows]

    def latest_saved_report(self, user_id: int, day) -> Draft | None:
        row = self.db.execute(
            "SELECT payload FROM drafts WHERE user_id=%s AND payload->>'status'='done' "
            "AND payload->>'day'=%s ORDER BY updated_at DESC,seq DESC LIMIT 1",
            (user_id, day.isoformat()),
        ).fetchone()
        return Draft.model_validate(row[0]) if row else None

    def active_draft(self, user_id: int) -> Draft | None:
        pending = self.pending_drafts(user_id, limit=1)
        return pending[0] if pending else None

    def save_operation(self, op: Operation) -> None:
        self.db.execute(
            "INSERT INTO operations(id,draft_id,payload) VALUES (%s,%s,%s) "
            "ON CONFLICT(id) DO UPDATE SET payload=EXCLUDED.payload",
            (op.id, op.draft_id, Jsonb(op.model_dump(mode="json"))),
        )

    def operation_for(self, draft_id: str) -> Operation | None:
        row = self.db.execute(
            "SELECT payload FROM operations WHERE draft_id=%s", (draft_id,)
        ).fetchone()
        return Operation.model_validate(row[0]) if row else None

    def daily_operations(self, day, spreadsheet_id: str) -> list[Operation]:
        rows = self.db.execute(
            "SELECT payload FROM operations WHERE payload->>'day'=%s "
            "AND payload->>'spreadsheet_id'=%s AND payload->>'sheets_done'='true' ORDER BY seq",
            (day.isoformat(), spreadsheet_id),
        ).fetchall()
        return [Operation.model_validate(row[0]) for row in rows]

    def pending_operation(self) -> Operation | None:
        row = self.db.execute(
            "SELECT payload FROM operations WHERE NOT (payload->>'sheets_done'='true' "
            "AND payload->>'bitrix_done'='true') ORDER BY seq LIMIT 1"
        ).fetchone()
        return Operation.model_validate(row[0]) if row else None

    def close(self) -> None:
        self.db.close()

    def web_token(self, draft: Draft) -> str:
        token = secrets.token_urlsafe(32)
        with self.db.transaction():
            self.db.execute("DELETE FROM web_links WHERE expires_at<%s", (time.time(),))
            self.db.execute(
                "INSERT INTO web_links VALUES (%s,%s,%s,%s)",
                (
                    hashlib.sha256(token.encode()).hexdigest(),
                    draft.id,
                    draft.user_id,
                    time.time() + 7 * 86400,
                ),
            )
        return token

    def from_web_token(self, draft_id: str, token: str) -> Draft:
        row = self.db.execute(
            "SELECT user_id FROM web_links WHERE token_hash=%s AND draft_id=%s AND expires_at>%s",
            (hashlib.sha256(token.encode()).hexdigest(), draft_id, time.time()),
        ).fetchone()
        if not row:
            raise UserError("Ссылка недействительна или истекла. Получите новую через /draft.")
        return self.get_draft(draft_id, row[0])
